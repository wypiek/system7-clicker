// Palette swaps: map of palette char -> replacement char.
const SWAPS = {
  gold: { b: 'y', G: 'o', g: 'y', B: 'w' },
  red: { b: 'r' },
  green: { b: 'e' },
  purple: { b: 'p' },
  pink: { b: 'm' },
  cyan: { b: 'c' },
  orange: { b: 'o' },
  dark: { b: 'd' },
  silver: { y: 'g', n: 'G' },
  ruby: { y: 'r', n: 'd' },
  emerald: { y: 'e', n: 'd' },
};

const _iconCache = {};

function iconURL(name, swap) {
  const key = name + '|' + (swap || '');
  if (_iconCache[key]) return _iconCache[key];
  const rows = ART[name] || ART.floppy;
  const h = rows.length;
  const w = rows[0].length;
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const ctx = c.getContext('2d');
  const map = swap ? SWAPS[swap] : null;
  for (let j = 0; j < h; j++) {
    for (let i = 0; i < w; i++) {
      let ch = rows[j][i];
      if (map && map[ch]) ch = map[ch];
      if (!ch || ch === '.' || !PALETTE[ch]) continue;
      ctx.fillStyle = PALETTE[ch];
      ctx.fillRect(i, j, 1, 1);
    }
  }
  _iconCache[key] = c.toDataURL();
  return _iconCache[key];
}

function iconImg(name, size = 32, swap = null, cls = '') {
  return `<img class="px ${cls}" src="${iconURL(name, swap)}" width="${size}" height="${size}" alt="" draggable="false">`;
}

